/**
 * Generates src/lib/pdf-font-data.ts with base64 data URIs for fonts and logo.
 * Run after updating font files: node scripts/gen-font-data.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'src', 'lib', 'pdf-font-data.ts');

const files = {
  FONT_REGULAR: { path: 'public/fonts/Poppins-Regular.ttf', mime: 'font/truetype' },
  FONT_MEDIUM:  { path: 'public/fonts/Poppins-Medium.ttf',  mime: 'font/truetype' },
  FONT_BOLD:    { path: 'public/fonts/Poppins-Bold.ttf',    mime: 'font/truetype' },
  LOGO_URL:     { path: 'public/Poppins.png',               mime: 'image/png' },
};

const lines = ['// Auto-generated by scripts/gen-font-data.js — do not edit manually', ''];
for (const [name, { path: rel, mime }] of Object.entries(files)) {
  const b64 = fs.readFileSync(path.join(root, rel)).toString('base64');
  lines.push(`export const ${name} = "data:${mime};base64,${b64}";`);
  lines.push('');
}

fs.writeFileSync(out, lines.join('\n'));
console.log(`[gen-font-data] ${out} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`);
